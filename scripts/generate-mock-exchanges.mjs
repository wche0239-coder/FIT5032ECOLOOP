// Generates src/data/mockExchanges.js and functions/demoExchanges.json — mock exchange history for the
// BR (D.3) interactive table. Same idea as a Mockaroo schema, but
// seeded so the data is identical every time it is regenerated.
// Run: node scripts/generate-mock-exchanges.mjs
import { writeFileSync } from 'node:fs'

let seed = 5032
const rand = () => ((seed = (seed * 1664525 + 1013904223) % 4294967296) / 4294967296)
const pick = (arr) => arr[Math.floor(rand() * arr.length)]

const items = {
  furniture: ['Bookshelf', 'Bedside table', 'Dining chairs (2)', 'Office chair', 'Coffee table'],
  clothing: ['Winter coat', 'Kids jackets bundle', 'Work shirts (5)', 'Rain boots'],
  'toys-baby': ['Pram', 'Wooden blocks set', 'High chair', 'Baby bath'],
  electronics: ['Desk monitor', 'Bluetooth speaker', 'Toaster', 'Kettle'],
  homewares: ['Ceramic mugs (6)', 'Cutlery set', 'Lamp', 'Picture frames'],
  packaging: ['Takeaway cups (200)', 'Shipping boxes (30)', 'Bubble wrap roll', 'Glass jars (24)'],
  food: ['Bread surplus', 'Pantry staples bundle', 'Fruit box seconds', 'Coffee beans (near date)'],
  books: ['Picture books (12)', 'Uni textbooks', 'Cookbooks', 'Novels box'],
  garden: ['Terracotta pots (6)', 'Seedling trays', 'Garden hose', 'Compost bin'],
}
const kgPer = { furniture: 9, clothing: 0.6, 'toys-baby': 1.1, electronics: 2.5, homewares: 0.8, packaging: 0.3, food: 0.9, books: 0.5, garden: 1.4 }
const suburbs = ['Box Hill', 'Carlton', 'Fitzroy', 'Brunswick', 'Richmond', 'Footscray', 'Coburg', 'St Kilda', 'Northcote', 'Collingwood', 'Clayton', 'Hawthorn']
const statuses = ['Completed', 'Completed', 'Completed', 'Pending', 'Cancelled']

const rows = []
for (let i = 1; i <= 86; i++) {
  const category = pick(Object.keys(items))
  const from = pick(suburbs)
  let to = pick(suburbs)
  if (to === from) to = pick(suburbs)
  const isFree = rand() < 0.55
  const day = new Date(Date.UTC(2026, 4, 1) + Math.floor(rand() * 150) * 86400000)
  rows.push({
    id: `EX-${String(i).padStart(4, '0')}`,
    date: day.toISOString().slice(0, 10),
    item: pick(items[category]),
    category,
    fromSuburb: from,
    toSuburb: to,
    type: isFree ? 'Free' : 'Sale',
    price: isFree ? 0 : Math.round((3 + rand() * 45) * 2) / 2,
    kgDiverted: Math.round(kgPer[category] * (0.6 + rand() * 1.8) * 10) / 10,
    status: pick(statuses),
  })
}

writeFileSync(
  new URL('../src/data/mockExchanges.js', import.meta.url),
  `// Generated by scripts/generate-mock-exchanges.mjs — mock data for BR (D.3).\n// Do not edit by hand; re-run the script instead.\nexport const mockExchanges = ${JSON.stringify(rows, null, 2)}\n`
)
// Same rows for the admin-only seed function (F.1 dashboard reads them from Firestore).
writeFileSync(new URL('../functions/demoExchanges.json', import.meta.url), JSON.stringify(rows, null, 2) + '\n')
console.log(`Wrote ${rows.length} rows`)
